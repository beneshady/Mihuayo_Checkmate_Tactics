const path = require('node:path'), fs = require('node:fs');
const { startServer } = require('../tests/us011-static-server.cjs');
const pw = require(path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
(async () => {
  const { port, close } = await startServer(path.join(__dirname, '..', 'web'));
  const base = 'http://127.0.0.1:' + port;
  const browser = await pw.chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, acceptDownloads: true });
  const page = await context.newPage();
  page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
  page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text()); });
  await page.goto(base + '/editor.html?smoke=1');
  await page.waitForFunction(() => !!window.__M0_MAP_EDITOR__);
  console.log('init status:', await page.locator('#editor-status').innerText());
  console.log('level inputs:', await page.locator('#level-code').inputValue(), '/', await page.locator('#level-name').inputValue());
  const [chooser] = await Promise.all([page.waitForEvent('filechooser'), page.locator('#import-file').click()]);
  await chooser.setFiles('D:\\Projects\\mihuayou\\develop_suzukaze\\MihuayoCheckmateTactics\\assets\\resources\\Levels\\level-01.json');
  await page.waitForFunction(() => document.getElementById('editor-status').textContent.includes('已导入'));
  console.log('import status:', await page.locator('#editor-status').innerText());
  const draft = await page.evaluate(() => window.__M0_MAP_EDITOR__.getDraft());
  console.log('draft:', draft.name, draft.levelCode, draft.levelName, Object.keys(draft.tiles).length, draft.units.length);
  await page.locator('#level-code').fill('level-smoke');
  await page.locator('#level-name').fill('冒烟关');
  const [dl] = await Promise.all([page.waitForEvent('download'), page.locator('#save-export').click()]);
  console.log('download:', dl.suggestedFilename());
  const out = path.join(__dirname, 'us011-smoke-download.json');
  await dl.saveAs(out);
  const doc = JSON.parse(fs.readFileSync(out, 'utf8'));
  console.log('doc:', doc.formatVersion, doc.meta, Object.keys(doc.map.tiles).length, doc.units.length, doc.rng, doc.turn, doc.result, doc.history);
  console.log('status:', await page.locator('#editor-status').innerText());
  await page.screenshot({ path: path.join(__dirname, 'us011-smoke.png'), fullPage: true });
  await browser.close(); await close();
})().catch((e) => { console.error('FAIL', e); process.exitCode = 1; });
