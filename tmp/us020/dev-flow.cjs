// US-020 dev probe: drive tutorial + camp through real browser interactions.
const path=require('node:path');
const pw=require(path.join(process.env.USERPROFILE,'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const base=process.env.M0_TEST_URL||'http://127.0.0.1:8777';
const log=(...a)=>console.log(...a);
(async()=>{
 const browser=await pw.chromium.launch({headless:true});
 const ctx=await browser.newContext({viewport:{width:1280,height:720}});
 const errors=[];ctx.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
 const p=await ctx.newPage();
 const cell=async to=>{const xy=await p.evaluate(t=>window.__M0_DEBUG__.grid.screenPoint(t),to);await p.mouse.click(xy.x,xy.y);};
 const hover=async to=>{const xy=await p.evaluate(t=>window.__M0_DEBUG__.grid.screenPoint(t),to);await p.mouse.move(xy.x,xy.y);};
 const step=async()=>p.evaluate(()=>window.M0Tutorial.progress());
 const st=async()=>p.evaluate(()=>window.__M0_DEBUG__.getState());
 await p.goto(base+'/');
 await p.waitForFunction(()=>window.M0Campaign?.info().view==='menu');
 await p.locator('#flow-new').click();
 await p.locator('#tutorial-enter').click();
 await p.waitForFunction(()=>window.M0Campaign.info().view==='battle');
 log('step',await step());
 await p.locator('#tutorial-ack').click();
 log('after ack',await step());
 await hover({x:1,y:3});
 await p.waitForTimeout(150);
 log('after hover enemy',await step());
 await p.locator('[data-unit="tut-rook"]').click();
 await cell({x:2,y:2});
 let s=await st();log('after rook move',await step(),'rook',JSON.stringify(s.units.find(u=>u.id==='tut-rook')));
 await p.locator('#btn-undo').click();
 s=await st();log('after undo',await step(),'rook',JSON.stringify(s.units.find(u=>u.id==='tut-rook')));
 await p.locator('[data-unit="tut-rook"]').click();
 await cell({x:2,y:2});
 log('after second move',await step());
 await p.locator('[data-unit="tut-spear"]').click();
 await cell({x:6,y:3});
 s=await st();log('after spear attack',await step(),'e2 alive',!!s.units.find(u=>u.id==='w1-2'),'kills',s.kills);
 await p.locator('#btn-end').click();
 await p.locator('#btn-confirm-yes').click();
 await p.waitForTimeout(200);
 s=await st();
 log('after end turn',JSON.stringify(await step()),'phase',s.phase,'turn',s.turn,'wave',s.wave,'kingHp',(s.units.find(u=>u.id==='king')||{}).hp);
 log('done dialog visible',await p.locator('#ov-tutorial').isVisible());
 await p.screenshot({path:'tmp/us020/s3-done.png'});
 if(await p.locator('#ov-tutorial').isVisible())await p.locator('#tutorial-done-ok').click();
 await p.waitForTimeout(300);
 log('view',await p.evaluate(()=>window.M0Campaign.info().view),'guide visible',await p.locator('#camp-guide').isVisible());
 log('camp info',JSON.stringify(await p.evaluate(()=>window.M0Campaign.info())));
 await p.screenshot({path:'tmp/us020/s4-camp.png'});
 log('camp summary',(await p.locator('#camp-summary').innerText()).replace(/\n+/g,' | '));
 log('pageerrors',JSON.stringify(errors));
 await browser.close();
})().catch(e=>{console.error('FAIL',e.stack);process.exitCode=1;});

